function getExample(infinitive, tense, pronoun, form) {
  const key = `${infinitive}|${tense}|${pronoun}`
  if (examples[key]) return examples[key]
  // Generic fallback for verbs not fully listed above
  const subj = pronoun === 'yo' ? 'Yo' : pronoun.charAt(0).toUpperCase() + pronoun.slice(1)
  return {
    es: `${subj} ${form} con frecuencia.`,
    en: `${pronoun} ${form} frequently.`,
  }
}

const tensesToSeed = [
  'preterite','imperfect','future','conditional',
  'present_subjunctive','imperfect_subjunctive',
  'present_perfect','imperative',
  'past_perfect','future_perfect','conditional_perfect',
  'present_perfect_subjunctive'
]

async function main() {
  console.log('Seeding verb tenses...')
  let total = 0

  for (const [infinitive, data] of Object.entries(verbData)) {
    const verb = await prisma.verb.findUnique({ where: { infinitive } })
    if (!verb) {
      console.warn(`Verb not found: ${infinitive}, skipping`)
      continue
    }

    for (const tense of tensesToSeed) {
      const forms = data[tense]
      if (!forms) continue

      const tensePronounList = tense === 'imperative' ? imperativePronouns : pronouns

      for (let i = 0; i < tensePronounList.length; i++) {
        const pronoun = tensePronounList[i]
        const form = forms[i]
        if (!form) continue

        const ex = getExample(infinitive, tense, pronoun, form)

        await prisma.verbConjugation.upsert({
          where: { verbId_tense_pronoun: { verbId: verb.id, tense, pronoun } },
          update: { form, exampleEs: ex.es, exampleEn: ex.en },
          create: { verbId: verb.id, tense, pronoun, form, exampleEs: ex.es, exampleEn: ex.en },
        })
        total++
      }
    }
    console.log(`  Seeded ${infinitive}`)
  }

  console.log(`Done! Upserted ${total} conjugations.`)
  await prisma.$disconnect()
}

main().catch(e => {
  console.error(e)
  prisma.$disconnect()
  process.exit(1)
})
